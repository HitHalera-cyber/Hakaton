// Уроки по шагам. Шаги проверяются микрофоном: сыграть аккорд N раз, сменить аккорды, сыграть бой в темп.

export type LessonStep =
  | { kind: 'info'; title: string; text: string; chord?: string }
  | { kind: 'chord'; title: string; chord: string; reps: number; tip?: string }
  | { kind: 'change'; title: string; pair: [string, string]; changes: number; tip?: string }
  | { kind: 'strum'; title: string; chord: string; patternId: string; bpm: number; bars: number; perBar: [number, number]; tip?: string };

export type LessonLevel = 'start' | 'base' | 'middle' | 'advanced' | 'theory';

export const LEVELS: { id: LessonLevel; title: string }[] = [
  { id: 'start', title: 'С нуля' },
  { id: 'base', title: 'Новичок' },
  { id: 'middle', title: 'Средний уровень' },
  { id: 'advanced', title: 'Продвинутый' },
  { id: 'theory', title: 'Теория — читать и слушать' },
];

export interface Lesson {
  id: string;
  level: LessonLevel;
  title: string;
  icon: string;
  description: string;
  steps: LessonStep[];
}

const chord = (c: string, tip?: string, reps = 3): LessonStep => ({ kind: 'chord', title: `Аккорд ${c}`, chord: c, reps, tip });
const info = (title: string, text: string, chord?: string): LessonStep => ({ kind: 'info', title, text, chord });
const strum = (
  chord: string,
  patternId: string,
  bpm: number,
  perBar: [number, number],
  title: string,
  tip?: string,
  bars = 4,
): LessonStep => ({ kind: 'strum', title, chord, patternId, bpm, bars, perBar, tip });
const change = (a: string, b: string, changes = 4, tip?: string): LessonStep => ({
  kind: 'change',
  title: `Смена ${a} ⇄ ${b}`,
  pair: [a, b],
  changes,
  tip,
});

