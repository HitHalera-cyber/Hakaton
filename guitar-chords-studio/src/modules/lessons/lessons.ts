// Уроки по шагам. Шаги проверяются микрофоном: сыграть аккорд N раз, сменить аккорды, сыграть бой в темп.

export type LessonStep =
  | { kind: 'info'; title: string; text: string; chord?: string }
  | { kind: 'chord'; title: string; chord: string; reps: number; tip?: string }
  | { kind: 'change'; title: string; pair: [string, string]; changes: number; tip?: string }
  | { kind: 'strum'; title: string; chord: string; patternId: string; bpm: number; bars: number; perBar: [number, number]; tip?: string };

export interface Lesson {
  id: string;
  title: string;
  icon: string;
  description: string;
  steps: LessonStep[];
}

const chord = (c: string, tip?: string, reps = 3): LessonStep => ({ kind: 'chord', title: `Аккорд ${c}`, chord: c, reps, tip });
const change = (a: string, b: string, changes = 4, tip?: string): LessonStep => ({
  kind: 'change',
  title: `Смена ${a} ⇄ ${b}`,
  pair: [a, b],
  changes,
  tip,
});

