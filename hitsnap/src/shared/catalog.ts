export function slugify(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9а-яё]+/gi, '-')
    .replace(/^-+|-+$/g, '')
}

function buildCatalog(rows: Row[]): Song[] {
  const seen = new Set<string>()
  const songs: Song[] = []
  for (const [artist, title, year, genre, lang] of rows) {
    const id = slugify(`${artist}-${title}`)
    if (seen.has(id)) continue
    seen.add(id)
    songs.push({
      id,
      artist,
      title,
      year,
      genre,
      lang: lang ?? 'en'
    })
  }
  return songs
}

export const CATALOG: Song[] = buildCatalog(ROWS)
